# -*- coding: utf-8 -*-
"""提示词模板（P3 结构设计 / P4 分节写正文）。

原则：模型只负责"理解与写作"，版式与编号由服务端决定；
所有事实性内容必须能在给定的原文块里找到，找不到就进"疑误清单"。
"""
import re

SYSTEM_PLAN = """你是会议纪要的结构设计师。给定一份逐字稿（已按块编号），设计交付稿的章节树与表格，不写正文。

硬约束：
1. 章节用「一、／（一）」两级（必要时第三级用「1.」）；章号从「一」连续、不缺号。
2. 每节必须给出 blocks：该节依据的原文块编号（整数数组）。不要凭印象编，必须来自给定编号。
3. 必须设计 3 张表：议题速览、共识与决策汇总、待办与责任分工。表格内容只能来自原文块。
   每张表 3—5 列（含"序号"；最后一列尽量是"出处"，用原文时间区间），不要把内部块号写进表格。
4. 时间区间（形如 13:24—13:30）若原文有，原样放入议题速览的"时间区间"列。
5. 原文里疑似转写误差（人名、术语、断句）放进 uncertain，不要在正文里擅自改正。
6. 只输出 JSON，不要解释、不要代码围栏。
7. **输出必须紧凑**（输出长度有硬上限）：
   - 章 3—7 个，每章节 1—4 个；每节 points ≤ 3 条、每条 ≤ 30 字；
   - 三张表每张最多 12 行、每格文字 ≤ 30 字；
   - 不要复述原文，不要写正文，不要输出任何多余字段。

JSON 结构：
{
  "title": "主标题（会议主题，不含"纪要"二字）",
  "subtitle": "副标题，如 ——某某会议纪要",
  "note": "说明行，如 整理形式：议题速览＋议题纪要＋共识与待办｜记录来源：xxx",
  "chapters": [
    {"no": "一", "heading": "会议概况",
     "sections": [{"no": "（一）", "heading": "基本信息", "blocks": [1, 2],
                   "points": ["该节要讲的 2-4 个要点，供写作参考"]}]}
  ],
  "tables": [
    {"caption": "表 1　议题速览", "anchor": "一",
     "columns": ["序号", "议题", "时间区间", "核心内容"],
     "rows": [["1", "…", "13:24—13:30", "…"]]}
  ],
  "uncertain": ["原文表述 → 疑点 → 建议"]
}"""

SYSTEM_WRITE = """你是公文风格的会议纪要撰写者。给定某一节的原文块与写作要点，写出该节正文。

硬约束：
1. 只写正文段落/项目符号，不要写任何标题（标题由系统加）。
2. 数字、金额、时间、型号、人名、单位一律照抄原文，不得换算、不得改写、不得新增。
3. 同一事实有多个口径时并列写，并标注出处（如 13:50—14:27）。
4. 决策分「已确认／待确认／建议」三类；"建议"必须显式标注是提炼而非原文。
5. 原文没有的内容不要补；不要写"综上所述""总而言之"。
6. 每个要点 1-2 句，控制在该节 5-12 行；术语沿用原文，不要换同义词。
7. 输出 markdown：项目符号用「- 」，重点词可用 **加粗**，不要用表格、不要用标题。
8. **绝对不要在正文里出现块号引用**（例如「（[74] 已确认口径）」「[77] 表述为」）。
   要标出处就写原文的时间区间（如 14:27—15:00）；没有时间区间就不标。"""

# 清理模型仍写出来的块号引用："（[74] xxx）" / "[77] 表述为" / "[12,13]"
BLOCK_REF_RE = re.compile(r"[（(]?\s*\[\s*\d+(?:\s*[,，、]\s*\d+)*\s*\]\s*[）)]?")


def plan_messages(outline_text: str, stats: dict) -> list[dict]:
    user = (
        "材料画像：%d 字符 / %d 个内容块 / 原标题 %d 个。\n\n"
        "逐字稿（按块编号，格式 [块号]（类型）内容节选——括号里是块类型，内容已截断，只为判断结构）：\n%s\n\n"
        "请按系统要求输出 JSON。记住：紧凑输出，块号必须取自上面的编号。"
        % (stats.get("chars", 0), stats.get("blocks", 0), stats.get("headings", 0), outline_text)
    )
    return [{"role": "system", "content": SYSTEM_PLAN}, {"role": "user", "content": user}]


def write_messages(chapter: str, section: str, points: list[str], blocks_text: str,
                   context: str = "") -> list[dict]:
    user = (
        "所属章节：%s\n本节标题：%s\n"
        "%s"
        "写作要点（供参考，事实以原文为准）：%s\n\n"
        "本节原文块：\n%s\n\n"
        "请写这一节的正文（只输出 markdown 正文）。"
        % (chapter, section,
           ("上下文说明：%s\n" % context) if context else "",
           "；".join(points) if points else "（无）",
           blocks_text)
    )
    return [{"role": "system", "content": SYSTEM_WRITE}, {"role": "user", "content": user}]
